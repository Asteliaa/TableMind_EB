def concentration_detail(conc):
    """Таблица вкладов игроков в показатели концентрации: доля, накопленная доля, вклад в HHI, отношение к лидеру."""
    lead = conc["shares"][0][1]
    cum = 0.0
    rows = []
    for d, v in conc["shares"]:
        cum += v
        rows.append([sw[d]["name"], sw[d]["type"], pct(v, 1), pct(cum, 1), num((v * 100) ** 2, 0), num(v / lead, 2),
                     num(float(raw[d]["global_rank"]), 0)])
    top3 = sum((v * 100) ** 2 for _, v in conc["shares"][:3])
    table("hhi_detail", "Вклад игроков в показатели концентрации релевантного трафика",
          ["Игрок", "Класс", "Доля", "Накопленная доля", "Вклад в HHI", "Отношение к лидеру", "Мировой ранг"], rows,
          f"Накопленная доля показывает, как формируются показатели CR3 и CR5: три крупнейших игрока дают {pct(sum(v for _, v in conc['shares'][:3]), 1)}, пять - {pct(sum(v for _, v in conc['shares'][:5]), 1)}. Вклад в индекс Херфиндаля - Хиршмана (доля в процентах в квадрате) у трех лидеров равен {num(top3, 0)} из {num(conc['hhi'], 0)}, то есть около {pct(top3 / conc['hhi'], 0)} концентрации создают три сайта; остальные девять дают менее половины. Относительный размер показывает, что второй игрок в {num(lead / conc['shares'][1][1], 1)} раза меньше лидера, а последние два (Spreadsheet Detective и CIMCON) составляют доли процента и на структуру рынка не влияют. Доминирования одного игрока нет: лидер владеет лишь {pct(lead, 0)} релевантного трафика, поэтому порог высокой концентрации (CR3 60 %, HHI 2 500) не достигается.")
    figure("conc_curve", "Рисунки/05_кривая_концентрации.png", "Доли игроков и накопленная доля релевантного трафика",
           "Кривая накопленной доли растет круто только на первых трех игроках и затем выравнивается: после пятого игрока добавляются менее трети трафика, поэтому длинный хвост из семи небольших сайтов конкуренцию заметно не усиливает. Ни один из показателей не достигает порога высокой концентрации, то есть рынок остается открытым для нового игрока с узкой специализацией.")
