def _gt_files():
    out = []
    for p in sorted((ROOT / "Материалы_собранные" / "GT").glob("*.txt")):
        h = {}
        for line in p.read_text(encoding="utf-8").splitlines():
            if line.startswith("data "):
                break
            if " " in line:
                k, v = line.split(" ", 1)
                h[k] = v
        out.append((p.name, h))
    return out


