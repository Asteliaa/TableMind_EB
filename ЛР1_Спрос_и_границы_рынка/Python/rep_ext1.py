def _md_tables(path):
    """Возвращает список (заголовок раздела, шапка, строки) для таблиц markdown-файла."""
    out, cur, head, rows, hdr = [], None, None, [], None
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        if line.startswith("## "):
            cur = line[3:].strip()
        if line.startswith("|---"):
            continue
        if line.startswith("| "):
            cells = [c.strip() for c in line.strip().strip("|").split(" | ")]
            if hdr is None:
                hdr = cells
            else:
                rows.append(cells)
        elif hdr is not None:
            out.append((cur, hdr, rows)); hdr, rows = None, []
    if hdr is not None:
        out.append((cur, hdr, rows))
    return out


