LONG = {k: v for k, v in STATUS.items() if len(k) > 12}


def map_formula(f: str) -> str:
    for k, v in STATUS.items():
        f = f.replace(f'"{k}"', f'"{v}"')
    return re.sub(r'"[^"]*"', lambda m: re.sub(r"EUR", "у.е.", m.group(0)), f)


def map_text(t: str) -> str:
    return STATUS.get(t, t)


def apply_md(text: str) -> str:
    out = []
    for line in text.split("\n"):
        if line.startswith("|") and not line.startswith("|---"):
            cells = line.split("|")
            for i in range(1, len(cells) - 1):
                s = cells[i].strip()
                if s in STATUS:
                    cells[i] = cells[i].replace(s, STATUS[s])
            line = "|".join(cells)
        for k, v in LONG.items():
            if k in line:
                line = line.replace(k, v)
        out.append(line)
    return "\n".join(out)
