def fix(s, instr=True):
    if s in EXACT:
        return EXACT[s]
    for a, b in RULES[:-1]:
        s = re.sub(a, b, s)
    m = re.match(r"^" + VERBS + r" (.+)$", s)
    if m and instr:
        s = cap(m.group(2))
    return s


def run(path):
    pythoncom.CoInitialize()
    xl = wc.DispatchEx("Excel.Application")
    xl.Visible = False
    xl.DisplayAlerts = False
    xl.ScreenUpdating = False
    n = 0
    try:
        wb = xl.Workbooks.Open(str(path))
        xl.Calculation = -4135
        for ws in wb.Worksheets:
            ur = ws.UsedRange
            f = ur.Formula
            if not isinstance(f, tuple):
                f = ((f,),)
            r0, c0 = ur.Row, ur.Column
            for i in range(ur.Rows.Count):
                for j in range(ur.Columns.Count):
                    v = f[i][j]
                    if isinstance(v, str) and v and not v.startswith("="):
                        nv = fix(v, bool(re.search(r"Инструкц|Методика|Справочн", ws.Name)) or (r0 + i) <= 3)
                        if nv != v:
                            ws.Cells(r0 + i, c0 + j).Value = nv
                            n += 1
            # даты-пометки как значения
            for i in range(ur.Rows.Count):
                for j in range(ur.Columns.Count):
                    c = ws.Cells(r0 + i, c0 + j)
                    t = c.Text
                    if isinstance(t, str) and re.match(r"^2026-05-0\d|^0[1-3]\.05\.2026", t) and c.HasFormula is False:
                        c.Value = "2026-10-03"
                        n += 1
        xl.Calculation = -4105
        wb.Save()
        wb.Close(False)
    finally:
        xl.Quit()
    print("OK", Path(path).name, "изменено ячеек", n)


if __name__ == "__main__":
    for a in sys.argv[1:]:
        run(a)
